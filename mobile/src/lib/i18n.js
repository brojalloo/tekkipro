const getValueByPath = (source, path) => path.split('.').reduce((current, key) => current?.[key], source);

export const getLocale = (language) => (language === 'en' ? 'en-US' : 'fr-FR');

export const translate = (language, key, params = {}) => {
  const template = getValueByPath(translations[language] || translations.fr, key) ?? getValueByPath(translations.fr, key) ?? key;
  if (typeof template !== 'string') return key;
  return template.replace(/\{\{\s*([^}]+)\s*\}\}/g, (_, name) => String(params[name.trim()] ?? ''));
};